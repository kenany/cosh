import { cosh } from 'cosh';
import { describe, expect, it } from 'vitest';

const sloppyTolerance = 100;
let ENDIAN = 0;
const f = new Float64Array([0, 0]);
const u = new Uint32Array(f.buffer);

function diff(a: number, b: number): number {
  f[0] = a;
  f[1] = b;
  return Math.abs(
    (u[3 - ENDIAN]! - u[1 - ENDIAN]!) * 0x1_00_00_00_00 +
      u[2 + ENDIAN]! -
      u[0 + ENDIAN]!
  );
}

if (diff(2, 4) === 0x10_00_00) {
  ENDIAN = 1;
}

function nearEqual(a: number, b: number, tolerance: number): boolean {
  if (!Number.isFinite(b)) {
    return false;
  }

  if (Number.isNaN(a)) {
    return false;
  }

  if (!Number.isFinite(a) && b * Math.sign(a) < Number.MAX_VALUE) {
    return false;
  }

  const target = b === 0 ? a * 0 : b;
  const err = diff(a, target);

  if (err > tolerance) {
    return false;
  }

  return true;
}

